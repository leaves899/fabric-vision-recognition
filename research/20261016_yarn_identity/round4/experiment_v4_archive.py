def delta(a,b):return np.abs((a-b+90)%180-90)

def tensor(p, sigma=1.6, integration=6):
    g=cv2.cvtColor(p,cv2.COLOR_BGR2GRAY).astype(np.float32)
    g=cv2.GaussianBlur(g,(0,0),sigma)
    dx=cv2.Sobel(g,cv2.CV_32F,1,0,ksize=3)
    dy=cv2.Sobel(g,cv2.CV_32F,0,1,ksize=3)
    jxx=cv2.GaussianBlur(dx*dx,(0,0),integration)
    jyy=cv2.GaussianBlur(dy*dy,(0,0),integration)
    jxy=cv2.GaussianBlur(dx*dy,(0,0),integration)
    a=(np.degrees(.5*np.arctan2(2*jxy,jxx-jyy))+90)%180
    coherence=np.sqrt((jxx-jyy)**2+4*jxy**2)/(jxx+jyy+1.e-6)
    energy=np.sqrt(jxx+jyy)
    return a,coherence,energy

def modes(p):
    # Angular peaks at two independently evidenced tangent orientations,
    # never generated by taking a perpendicular of the first mode.
    weights=None
    for sig,integ,weight in [(1.0,3.0,.7),(1.8,5.0,1.0),(3.0,8.0,.5)]:
        a,c,e=tensor(p,sig,integ)
        w=np.clip(c,0,1)*np.sqrt(np.maximum(e,0))*weight
        # Use only center 450px to avoid padded/blurred edges
        h=np.bincount(np.rint(a[30:-30,30:-30]).astype(int).ravel()%180,
                      weights=w[30:-30,30:-30].ravel(),minlength=180)
        weights=h if weights is None else weights+h
    sm=gaussian_filter(weights,3.5,mode='wrap')
    found=[]
    for k in np.argsort(sm)[::-1]:
        if all(delta(k,x)>=38 for x in found):found.append(int(k))
        if len(found)>=2:break
    return sorted(found),sm

def ribbon_segments(p,theta,min_length=15):
    """Candidate ribbon cores from symmetric opposing intensity edges, irrespective of interior color.
    Geometric width is locally searched, not assumed. Results not yarn truth.
    """
    h,w=p.shape[:2]; c=((w-1)/2,(h-1)/2)
    M=cv2.getRotationMatrix2D(c,float(theta),1)
    inv=cv2.invertAffineTransform(M)
    rp=cv2.warpAffine(p,M,(w,h),flags=cv2.INTER_LINEAR,borderMode=cv2.BORDER_REFLECT_101)
    lum=cv2.cvtColor(rp,cv2.COLOR_BGR2GRAY).astype(np.float32)
    lum=cv2.GaussianBlur(lum,(0,0),2.0)
    dy=cv2.Sobel(lum,cv2.CV_32F,0,1,ksize=3)
    best=np.zeros((h,w),np.float32);win=np.zeros((h,w),np.uint8)
    for half in (6,9,13,17):
        # Symmetric pair of opposing gradient transitions encloses a ribbon;
        # keeps bright *or* dark ribs, so a white highlight in a blue yarn is allowed.
        upper=np.roll(dy,half,axis=0);lower=np.roll(dy,-half,axis=0)
        raw=np.where((upper*lower<0),np.minimum(np.abs(upper),np.abs(lower)),0)
        raw[:half+2,:]=0;raw[-half-2:,:]=0
        # Penalize asymmetric or structureless false pairing.
        raw=cv2.GaussianBlur(raw,(0,0),sigmaX=9,sigmaY=1.2)
        update=raw>best
        best[update]=raw[update]
        win[update]=half
    # NMS along normal; a column-wise peak is a potential ribbon center
    local_max=cv2.dilate(best,np.ones((9,1),np.uint8))
    valid=best[20:-20,20:-20]
    nonzero=valid[valid>0]
    cutoff=float(np.percentile(nonzero,70)) if len(nonzero)>500 else float('inf')
    center=((best>=local_max-1e-4)&(best>cutoff)).astype(np.uint8)
    center[:20,:]=0;center[-20:,:]=0;center[:,:20]=0;center[:,-20:]=0
    # Close only small gaps along the proposed yarn axis; no artificial long trajectories.
    center=cv2.morphologyEx(center,cv2.MORPH_CLOSE,np.ones((1,11),np.uint8))
    n,lab,stats,cent=cv2.connectedComponentsWithStats(center,8)
    pts=[]
    for i in range(1,n):
        x,y,bw,bh,area=stats[i]
        if bw<min_length or area<min_length or bh>19:continue
        yy,xx=np.where(lab[y:y+bh,x:x+bw]==i)
        yy=yy+y;xx=xx+x
        vals=best[yy,xx]
        a=float(np.average(xx,weights=vals+1.e-5));b=float(np.average(yy,weights=vals+1.e-5))
        start=np.array([max(0,int(x)),int(round(b)),1.]);end=np.array([min(w-1,int(x+bw-1)),int(round(b)),1.])
        xy=np.array([a,b,1])
        pos=inv@xy;start0=inv@start;end0=inv@end
        pts.append({'x':round(float(pos[0]),2),'y':round(float(pos[1]),2),
                    'start':np.round(start0,2).tolist(),'end':np.round(end0,2).tolist(),
                    'length_px':int(bw),'width_evidence_px':round(float(2*np.median(win[yy,xx])),2),
                    'edge_pair_score':round(float(np.median(vals)),3),
                    'theta_deg':float(theta)})
    return pts,best,center,M,cutoff

def color_only_ref(p):
    f=p.astype(np.float32)
    b,g,r=cv2.split(f)
    Y=cv2.cvtColor(p,cv2.COLOR_BGR2GRAY)
    return ((b-r>20)&(g-r>5)&(Y>75)&(Y<185)).astype(np.uint8)

def draw(p,families,old=None):
    out=p.copy();clr=[(40,210,255),(80,245,75)]
    for j,fam in enumerate(families):
        for z in fam['segments']:
            a=tuple(np.round(z['start']).astype(int));b=tuple(np.round(z['end']).astype(int))
            cv2.line(out,a,b,clr[j],2,cv2.LINE_AA)
            cv2.circle(out,tuple(np.round([z['x'],z['y']]).astype(int)),2,clr[j],-1,cv2.LINE_AA)
    return out

def associate(fam):
    """Hypothesized same-yarn connections with one-to-one and competing-match rejection.
    This is still ONLY geometrical, not a proof of physical same-yarn identity.
    """
    seg=fam['segments'];theta=np.deg2rad(fam['theta'])
    if len(seg)<2:return []
    u=np.array([np.cos(theta),np.sin(theta)])
    n=np.array([-np.sin(theta),np.cos(theta)])
    xy=np.array([[z['x'],z['y']] for z in seg]);U=xy@u;N=xy@n
    costs=np.full((len(seg),len(seg)),1e4,float)
    for i in range(len(seg)):
      for j in range(len(seg)):
        gap=U[j]-U[i]-.5*(seg[i]['length_px']+seg[j]['length_px'])
        cross=abs(N[j]-N[i])
        allowed_cross=min(9., .25*(seg[i]['width_evidence_px']+seg[j]['width_evidence_px']))
        if 4<=gap<=45 and cross<=allowed_cross:
            costs[i,j]=cross/allowed_cross + gap/45 + abs(seg[i]['width_evidence_px']-seg[j]['width_evidence_px'])/20
    ai,bj=linear_sum_assignment(costs)
    result=[]
    for i,j in zip(ai,bj):
        if costs[i,j]>=0.85:continue
        row_other=np.delete(costs[i],j);col_other=np.delete(costs[:,j],i)
        other=min(float(row_other.min()) if len(row_other) else 1e4,
                  float(col_other.min()) if len(col_other) else 1e4)
        margin=other-costs[i,j]
        # If similarly good alternative paths exist, abstain rather than making a false link.
        if margin<0.16:continue
        result.append({'source':int(i),'target':int(j),
                       'cost':round(float(costs[i,j]),3),
                       'alternative_margin':round(float(margin),3) if other<1e4 else None,
                       'kind':'TENTATIVE; geometry-only; no verified physical identity'})
    return result

def experiment(name,p,save=True):
    th,pro=modes(p)
    fams=[]
    for theta in th:
        segments,heat,mask,M,cutoff=ribbon_segments(p,theta)
        fam={'theta':float(theta),'segments':segments,'mask':mask,'heat':heat,'cutoff':cutoff}
        fam['links']=associate(fam)
        fams.append(fam)
    if save:
        compare=draw(p,fams)
        masks=[]
        for i,fam in enumerate(fams):
            rot=cv2.warpAffine(fam['mask']*255,cv2.invertAffineTransform(cv2.getRotationMatrix2D(((p.shape[1]-1)/2,(p.shape[0]-1)/2),fam['theta'],1)),(p.shape[1],p.shape[0]),flags=cv2.INTER_NEAREST)
            masks.append(rot)
        old=color_only_ref(p)
        oldvis=cv2.cvtColor(old*255,cv2.COLOR_GRAY2BGR)
        o=p.copy();o[old>0]=(o[old>0].astype(float)*.5+np.array([240,150,60])*.5).astype(np.uint8)
        cc=compare.copy()
        cv2.putText(o,'OLD: pure-blue pixel criterion',(12,32),cv2.FONT_HERSHEY_SIMPLEX,.68,(255,255,255),2)
        cv2.putText(cc,f'NEW: two geometric orientations {th}',(12,32),cv2.FONT_HERSHEY_SIMPLEX,.68,(255,255,255),2)
        cv2.imwrite(str(ROOT/f'{name}_old_vs_new.jpg'),cv2.hconcat([p,o,cc]),[cv2.IMWRITE_JPEG_QUALITY,91])
        for j,m in enumerate(masks):cv2.imwrite(str(ROOT/f'{name}_family{j+1}_coremask.png'),m)
        cv2.imwrite(str(ROOT/f'{name}_overlay.jpg'),compare,[cv2.IMWRITE_JPEG_QUALITY,95])
    summary={'angles_deg':th,'candidate_counts':[len(f['segments']) for f in fams],
             'candidate_covered_lengths_px':[int(sum(z['length_px'] for z in f['segments'])) for f in fams],
             'link_hypotheses':[len(f['links']) for f in fams],
             'blue_color_fraction_pct':round(100*color_only_ref(p).mean(),2),
             'caveat':'geometry candidates; NOT verified yarn instance identities or true yarn count'}
    return summary,fams

